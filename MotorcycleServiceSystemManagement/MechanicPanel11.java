    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:

int row = tblMechanic.getSelectedRow();
int col = tblMechanic.getSelectedColumn();

if (row == -1 || col == -1) {
    JOptionPane.showMessageDialog(this,
            "Please select a cell to update.");
    return;
}

if (col == 0) {
    JOptionPane.showMessageDialog(this,
            "Mechanic ID cannot be updated.");
    return;
}

String[] columns = {
    "MechanicID", "FirstName", "LastName",
    "ContactNumber", "Specialization"
};

String columnName = columns[col];

int modelRow = tblMechanic.convertRowIndexToModel(row);
Object currentValue = tblMechanic.getValueAt(row, col);

String newValue;

if (col == 4) {
    String[] specializations = {
        "Engine Repair",
        "Brake Repair",
        "Electrical Repair",
        "Transmission Repair",
        "General Maintenance",
        "Tire and Wheel Service"
    };

    newValue = (String) JOptionPane.showInputDialog(
            this,
            "Select new specialization:",
            "Update Specialization",
            JOptionPane.QUESTION_MESSAGE,
            null,
            specializations,
            currentValue
    );

    if (newValue == null) {
        return;
    }
} else {
    newValue = JOptionPane.showInputDialog(
            this,
            "Enter new value:",
            currentValue
    );

    if (newValue == null) {
        return;
    }

    newValue = newValue.trim();

    if (newValue.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Value cannot be empty.");
        return;
    }
}

int mechanicID = Integer.parseInt(
        tblMechanic.getModel().getValueAt(modelRow, 0).toString()
);

String sql = "UPDATE mechanic SET " + columnName
        + " = ? WHERE MechanicID = ?";

try (
    java.sql.Connection con = database.DBConnection.getConnection();
    java.sql.PreparedStatement pst = con.prepareStatement(sql)
) {
    pst.setString(1, newValue);
    pst.setInt(2, mechanicID);

    int updated = pst.executeUpdate();

    if (updated > 0) {
        JOptionPane.showMessageDialog(this,
                "Mechanic updated successfully!");
        loadMechanics();
    } else {
        JOptionPane.showMessageDialog(this,
                "No mechanic record was updated.");
    }

} catch (java.sql.SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Error updating mechanic: " + e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
        // TODO add your handling code here:
        
int selectedRow = tblMechanic.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(this, "Please select a mechanic first.");
    return;
}

int modelRow = tblMechanic.convertRowIndexToModel(selectedRow);
int mechanicID = Integer.parseInt(
    tblMechanic.getModel().getValueAt(modelRow, 0).toString()
);

int confirm = JOptionPane.showConfirmDialog(
    this,
    "Are you sure you want to archive this mechanic?",
    "Confirm Archive",
    JOptionPane.YES_NO_OPTION
);

if (confirm != JOptionPane.YES_OPTION) {
    return;
}

String sql = "UPDATE mechanic SET IsArchived = 1 WHERE MechanicID = ?";

try (java.sql.Connection con = database.DBConnection.getConnection();
     java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

    pst.setInt(1, mechanicID);

    if (pst.executeUpdate() > 0) {
        JOptionPane.showMessageDialog(this, "Mechanic archived successfully!");
        loadMechanics();
    } else {
        JOptionPane.showMessageDialog(this, "Mechanic not found.");
    }

} catch (java.sql.SQLException e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}

    }//GEN-LAST:event_btnRemoveActionPerformed


