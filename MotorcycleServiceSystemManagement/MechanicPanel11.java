private void loadMechanics() {
    String sql = "SELECT MechanicID, FirstName, LastName, "
            + "ContactNumber, Specialization FROM mechanic WHERE IsArchived = 0";

    try (
        java.sql.Connection con = database.DBConnection.getConnection();
        java.sql.PreparedStatement pst = con.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery()
    ) {
        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) tblMechanic.getModel();

        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("MechanicID"),
                rs.getString("FirstName"),
                rs.getString("LastName"),
                rs.getString("ContactNumber"),
                rs.getString("Specialization")
            });
        }

    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error loading mechanics: " + e.getMessage());
    }
}


private void setupSearchPlaceholder() {
    String placeholder = "Search mechanics...";

    TXTSEARCH.setText(placeholder);
    TXTSEARCH.setForeground(java.awt.Color.GRAY);

    TXTSEARCH.addFocusListener(new java.awt.event.FocusAdapter() {
        @Override
        public void focusGained(java.awt.event.FocusEvent evt) {
            if (TXTSEARCH.getText().equals(placeholder)) {
                TXTSEARCH.setText("");
                TXTSEARCH.setForeground(java.awt.Color.BLACK);
            }
        }

        @Override
        public void focusLost(java.awt.event.FocusEvent evt) {
            if (TXTSEARCH.getText().trim().isEmpty()) {
                TXTSEARCH.setText(placeholder);
                TXTSEARCH.setForeground(java.awt.Color.GRAY);
            }
        }
    });
}


