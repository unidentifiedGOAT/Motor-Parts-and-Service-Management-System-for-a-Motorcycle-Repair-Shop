    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
   
String serviceName = TXTSERVICENAME.getText().trim();
String description = TXTDESCRIPTION.getText().trim();
String feeText = TXTSERVICEFEE.getText().trim();

if (serviceName.isEmpty() || description.isEmpty()
        || feeText.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Please fill in all fields.");
    return;
}

java.math.BigDecimal fee;

try {
    fee = new java.math.BigDecimal(feeText);

    if (fee.compareTo(java.math.BigDecimal.ZERO) <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Service fee must be greater than zero.");
        return;
    }
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter a valid service fee.");
    return;
}

String sql = "INSERT INTO service "
        + "(ServiceName, Description, ServiceFee) "
        + "VALUES (?, ?, ?)";

try (java.sql.Connection con =
        database.DBConnection.getConnection();
     java.sql.PreparedStatement pst =
        con.prepareStatement(sql)) {

    pst.setString(1, serviceName);
    pst.setString(2, description);
    pst.setBigDecimal(3, fee);

    pst.executeUpdate();
    loadServices();

    javax.swing.JOptionPane.showMessageDialog(
            this, "Service saved successfully!");

    TXTSERVICENAME.setText("");
    TXTDESCRIPTION.setText("");
    TXTSERVICEFEE.setText("");

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Save failed: " + e.getMessage());
}
    }//GEN-LAST:event_btnSaveActionPerformed

    private void BTNSEARCHActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNSEARCHActionPerformed
        // TODO add your handling code here:        
    
String search = TXTSEARCH.getText().trim();

if (search.isEmpty()
        || search.equalsIgnoreCase("Search service...")) {
    loadServices();
    return;
}

String sql = "SELECT ServiceID, ServiceName, Description, ServiceFee "
        + "FROM service "
        + "WHERE IsArchived = 0 AND ("
        + "CAST(ServiceID AS CHAR) LIKE ? "
        + "OR ServiceName LIKE ? "
        + "OR Description LIKE ? "
        + "OR CAST(ServiceFee AS CHAR) LIKE ?)";

try (
    java.sql.Connection con = database.DBConnection.getConnection();
    java.sql.PreparedStatement pst = con.prepareStatement(sql)
) {
    String keyword = "%" + search + "%";

    for (int i = 1; i <= 4; i++) {
        pst.setString(i, keyword);
    }

    try (java.sql.ResultSet rs = pst.executeQuery()) {
        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) tblService.getModel();

        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("ServiceID"),
                rs.getString("ServiceName"),
                rs.getString("Description"),
                rs.getBigDecimal("ServiceFee")
            });
        }

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No service found.");
        }
    }

} catch (java.sql.SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Error searching services: " + e.getMessage());
}

    }//GEN-LAST:event_BTNSEARCHActionPerformed

