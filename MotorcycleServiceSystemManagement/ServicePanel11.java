private void loadServices() {
    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel)
            tblService.getModel();

    model.setRowCount(0);

    String sql = "SELECT ServiceID, ServiceName, "
        + "Description, ServiceFee FROM service "
        + "WHERE IsArchived = 0";

    try (java.sql.Connection con =
            database.DBConnection.getConnection();
         java.sql.PreparedStatement pst =
            con.prepareStatement(sql);
         java.sql.ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("ServiceID"),
                rs.getString("ServiceName"),
                rs.getString("Description"),
                rs.getBigDecimal("ServiceFee")
            });
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Failed to load services: "
                + e.getMessage());
    }
}
 
private void setupSearchPlaceholder() {
    String placeholder = "Search service...";

    TXTSEARCH.setText(placeholder);
    TXTSEARCH.setForeground(java.awt.Color.GRAY);

    TXTSEARCH.addFocusListener(new java.awt.event.FocusAdapter() {
        @Override
        public void focusGained(java.awt.event.FocusEvent evt) {
            if (TXTSEARCH.getText().equals(placeholder)) {
                TXTSEARCH.setText("");
                TXTSEARCH.setForeground(java.awt.Color.BLACK);
            }
        }

        @Override
        public void focusLost(java.awt.event.FocusEvent evt) {
            if (TXTSEARCH.getText().trim().isEmpty()) {
                TXTSEARCH.setText(placeholder);
                TXTSEARCH.setForeground(java.awt.Color.GRAY);
            }
        }
    });
}


