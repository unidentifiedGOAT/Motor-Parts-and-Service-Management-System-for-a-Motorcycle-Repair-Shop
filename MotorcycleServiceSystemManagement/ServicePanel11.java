    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:

int row = tblService.getSelectedRow();
int col = tblService.getSelectedColumn();

if (row == -1 || col == -1) {
    JOptionPane.showMessageDialog(this,
            "Please select a cell to update.");
    return;
}

int modelRow = tblService.convertRowIndexToModel(row);
int modelCol = tblService.convertColumnIndexToModel(col);

// Service ID cannot be changed
if (modelCol == 0) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Service ID cannot be changed.");
    return;
}

String[] columnNames = {
    "Service ID", "Service Name", "Description", "Service Fee"
};

String oldValue = tblService.getValueAt(row, col).toString();

String newValue = javax.swing.JOptionPane.showInputDialog(
        this, "Enter new " + columnNames[col] + ":",
        oldValue);

if (newValue == null) {
    return;
}

newValue = newValue.trim();

if (newValue.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Value cannot be empty.");
    return;
}

int serviceID = Integer.parseInt(
        tblService.getValueAt(row, 0).toString());

String column;

switch (modelCol) {
    case 1:
        column = "ServiceName";
        break;
    case 2:
        column = "Description";
        break;
    case 3:
        column = "ServiceFee";
        break;
    default:
        return;
}

java.math.BigDecimal fee = null;

if (col == 3) {
    try {
        fee = new java.math.BigDecimal(newValue);

        if (fee.compareTo(java.math.BigDecimal.ZERO) <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Service fee must be greater than zero.");
            return;
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Please enter a valid service fee.");
        return;
    }
}

String sql = "UPDATE service SET " + column
        + " = ? WHERE ServiceID = ?";

try (java.sql.Connection con =
        database.DBConnection.getConnection();
     java.sql.PreparedStatement pst =
        con.prepareStatement(sql)) {

    if (col == 3) {
        pst.setBigDecimal(1, fee);
    } else {
        pst.setString(1, newValue);
    }

    pst.setInt(2, serviceID);

    int updated = pst.executeUpdate();

    if (updated > 0) {
        loadServices();

        javax.swing.JOptionPane.showMessageDialog(
                this, columnNames[col]
                + " updated successfully!");
    }

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Update failed: " + e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
        // TODO add your handling code here:
        
int selectedRow = tblService.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(this, "Please select a service first.");
    return;
}

int modelRow = tblService.convertRowIndexToModel(selectedRow);
int serviceID = Integer.parseInt(
    tblService.getModel().getValueAt(modelRow, 0).toString()
);

int confirm = JOptionPane.showConfirmDialog(
    this,
    "Are you sure you want to archive this service?",
    "Confirm Archive",
    JOptionPane.YES_NO_OPTION
);

if (confirm != JOptionPane.YES_OPTION) {
    return;
}

String sql = "UPDATE service SET IsArchived = 1 WHERE ServiceID = ?";

try (java.sql.Connection con = database.DBConnection.getConnection();
     java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

    pst.setInt(1, serviceID);

    if (pst.executeUpdate() > 0) {
        JOptionPane.showMessageDialog(this, "Service archived successfully!");
        loadServices();
    } else {
        JOptionPane.showMessageDialog(this, "Service not found.");
    }

} catch (java.sql.SQLException e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}

    }//GEN-LAST:event_btnRemoveActionPerformed


