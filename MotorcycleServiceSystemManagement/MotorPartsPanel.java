private void loadParts() {
    String sql = "SELECT PartID, PartName, Brand, Category, StockQuantity, Price "
           + "FROM parts WHERE IsArchived = 0";

    try (
        java.sql.Connection con = database.DBConnection.getConnection();
        java.sql.PreparedStatement pst = con.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery()
    ) {
        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) tblParts.getModel();

        model.setRowCount(0);

        while (rs.next()) {
           model.addRow(new Object[]{
        rs.getInt("PartID"),
        rs.getString("PartName"),
        rs.getString("Brand"),
        rs.getString("Category"),
        rs.getInt("StockQuantity"),
        rs.getBigDecimal("Price")
    });        
   
    }

    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error loading parts: " + e.getMessage());
    }
}

