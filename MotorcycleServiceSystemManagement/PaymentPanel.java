private void loadTransactionCombo() {
    String sql =
        "SELECT st.TransactionID, c.FirstName, c.LastName "
      + "FROM service_transaction st "
      + "JOIN motorcycle m ON st.MotorcycleID = m.MotorcycleID "
      + "JOIN customer c ON m.CustomerID = c.CustomerID "
      + "ORDER BY st.TransactionID DESC";

    try (
        java.sql.Connection con =
            database.DBConnection.getConnection();
        java.sql.PreparedStatement pst =
            con.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery()
    ) {
        CBXTRANSACTIONID.removeAllItems();
        CBXTRANSACTIONID.addItem("-- Select Transaction --");

        while (rs.next()) {
            String item = rs.getInt("TransactionID") + " - "
                + rs.getString("FirstName") + " "
                + rs.getString("LastName");

            CBXTRANSACTIONID.addItem(item);
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Error loading transactions: " + e.getMessage()
        );
    }
}

private void loadPayments() {
    
String sql =
    "SELECT p.PaymentID, "
  + "CONCAT(c.FirstName, ' ', c.LastName) AS CustomerName, "
  + "p.TransactionID, p.PaymentDate, p.AmountPaid, p.PaymentMethod "
  + "FROM payment p "
  + "JOIN service_transaction st ON p.TransactionID = st.TransactionID "
  + "JOIN motorcycle m ON st.MotorcycleID = m.MotorcycleID "
  + "JOIN customer c ON m.CustomerID = c.CustomerID "
  + "WHERE p.IsArchived = 0 "
  + "AND st.IsArchived = 0 "
  + "AND m.IsArchived = 0 "
  + "AND c.IsArchived = 0 "
  + "ORDER BY p.PaymentID DESC";


    try (
        java.sql.Connection con = database.DBConnection.getConnection();
        java.sql.PreparedStatement pst = con.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery()
    ) {
        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblPayment.getModel();

        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("PaymentID"),
                rs.getString("CustomerName"),
                rs.getInt("TransactionID"),
                rs.getDate("PaymentDate"),
                rs.getBigDecimal("AmountPaid"),
                rs.getString("PaymentMethod")
            });
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Error loading payments: " + e.getMessage()
        );
    }
}

