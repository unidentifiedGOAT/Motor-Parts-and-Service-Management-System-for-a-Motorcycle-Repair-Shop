    private void tblPaymentMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPaymentMouseClicked
        // TODO add your handling code here:
    int row = tblPayment.getSelectedRow();

    if (row == -1) {
        return;
    }

    CBXTRANSACTIONID.setSelectedIndex(0);

    String transactionID =
            tblPayment.getValueAt(row, 2).toString();

    for (int i = 1; i < CBXTRANSACTIONID.getItemCount(); i++) {
        String item = CBXTRANSACTIONID.getItemAt(i);

        if (item.startsWith(transactionID + " - ")) {
            CBXTRANSACTIONID.setSelectedIndex(i);
            break;
        }
    }

    TXTPAYMENTDATE.setText(
            tblPayment.getValueAt(row, 3).toString());

    TXTAMOUNTPAID.setText(
            tblPayment.getValueAt(row, 4).toString());

    CBXPAYMENTMETHOD.setSelectedItem(
            tblPayment.getValueAt(row, 5).toString());
    }//GEN-LAST:event_tblPaymentMouseClicked

