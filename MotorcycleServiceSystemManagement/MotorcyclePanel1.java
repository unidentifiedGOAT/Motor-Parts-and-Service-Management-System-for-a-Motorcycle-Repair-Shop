private void loadCustomerCombo() {
    DefaultComboBoxModel<String> model =
            new DefaultComboBoxModel<>();

    String sql = "SELECT CustomerID, FirstName, LastName "
               + "FROM customer ORDER BY CustomerID";

    try (Connection con = database.DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {
            int id = rs.getInt("CustomerID");
            String firstName = rs.getString("FirstName");
            String lastName = rs.getString("LastName");

            model.addElement(id + " - "
                    + firstName + " " + lastName);
        }

        CBXCUSTOMERID.setModel(model);

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Failed to load customers: "
                + e.getMessage());
    }
}


private void loadMotorcycles() {
    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel)
            tblMotorcycles.getModel();

    model.setRowCount(0);

   String sql = "SELECT MotorcycleID, CustomerID, "
        + "Brand, Model, PlateNumber "
        + "FROM motorcycle WHERE IsArchived = 0";

    try (java.sql.Connection con =
            database.DBConnection.getConnection();
         java.sql.PreparedStatement pst =
            con.prepareStatement(sql);
         java.sql.ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("MotorcycleID"),
                rs.getInt("CustomerID"),
                rs.getString("Brand"),
                rs.getString("Model"),
                rs.getString("PlateNumber")
            });
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Failed to load motorcycles: "
                + e.getMessage());
    }
}

private void setupSearchPlaceholder() {
    String placeholder = "Search motorcycle...";

    TXTSEARCH.setText(placeholder);
    TXTSEARCH.setForeground(java.awt.Color.GRAY);

    TXTSEARCH.addFocusListener(new java.awt.event.FocusAdapter() {
        @Override
        public void focusGained(java.awt.event.FocusEvent evt) {
            if (TXTSEARCH.getText().equals(placeholder)) {
                TXTSEARCH.setText("");
                TXTSEARCH.setForeground(java.awt.Color.BLACK);
            }
        }

        @Override
        public void focusLost(java.awt.event.FocusEvent evt) {
            if (TXTSEARCH.getText().trim().isEmpty()) {
                TXTSEARCH.setText(placeholder);
                TXTSEARCH.setForeground(java.awt.Color.GRAY);
            }
        }
    });
}


